async function deleteSessionList() {
  try {
    console.log("🗑️  Session Deletion Script");
    console.log("============================");

    if (sessionIds.length === 0) {
      console.log(
        "❌ No session IDs found. Please add session IDs to the array in the script."
      );
      return;
    }

    console.log(`🔍 Found ${sessionIds.length} session IDs to delete:`);
    console.log(`📋 First few: ${sessionIds.slice(0, 3).join(", ")}...`);

    console.log("\n🗑️  Deleting sessions from database...");

    // Delete all sessions with these IDs
    const deletedSessions = await prisma.practiceSession.deleteMany({
      where: {
        id: {
          in: sessionIds,
        },
      },
    });

    console.log("\n📈 Summary:");
    console.log(`  🔍 Provided: ${sessionIds.length} session IDs`);
    console.log(`  ✅ Successfully deleted: ${deletedSessions.count} sessions`);
    console.log(
      `  📊 Difference: ${
        sessionIds.length - deletedSessions.count
      } (likely already deleted or non-existent)`
    );

    if (deletedSessions.count > 0) {
      console.log(
        "🎉 Sessions have been successfully deleted from the database!"
      );
    } else {
      console.log(
        "ℹ️  No sessions were deleted (they may have already been removed)"
      );
    }
  } catch (error) {
    console.error("❌ Error during deletion:", error);
  } finally {
    await prisma.$disconnect();
  }
}

