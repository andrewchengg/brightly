const StudentListPage = async ({
  searchParams,
}: {
  searchParams: { [key: string]: string } | undefined;
}) => {
  const page = searchParams?.page ? parseInt(searchParams.page) : 1;

  // Build query with search parameters
  const query: Prisma.StudentWhereInput = {};

  if (searchParams) {
    if (searchParams.search) {
      query.OR = [
        { name: { contains: searchParams.search, mode: "insensitive" } },
        { surname: { contains: searchParams.search, mode: "insensitive" } },
        { email: { contains: searchParams.search, mode: "insensitive" } },
        { username: { contains: searchParams.search, mode: "insensitive" } },
      ];
    }

    if (searchParams.classId) {
      query.class = { id: parseInt(searchParams.classId) };
    }

    if (searchParams.grade) {
      query.grade = { id: parseInt(searchParams.grade) };
    }
  }

  const [data, count] = await prisma.$transaction([
    prisma.student.findMany({
      where: query,
      include: {
        grade: true,
        class: true,
      },
      take: ITEM_PER_PAGE,
      skip: ITEM_PER_PAGE * (page - 1),
    }),
    prisma.student.count({ where: query }),
  ]);

  // Fetch grades and classes for the student form
  const [grades, classes] = await prisma.$transaction([
    prisma.grade.findMany({
      select: {
        id: true,
        level: true,
      },
    }),
    prisma.class.findMany({
      select: {
        id: true,
        name: true,
        capacity: true,
        _count: {
          select: { students: true },
        },
      },
    }),
  ]);

  const relatedData = { grades, classes };

  return (
    <div className="bg-white p-4 rounded-md flex-1 m-4 mt-0">
      {/* TOP */}
      <div className="flex items-center justify-between">
        <h1 className="hidden md:block text-lg font-semibold">All Students</h1>
        <div className="flex flex-col md:flex-row items-center gap-4 w-full md:w-auto">
          <TableSearch />
          <div className="flex items-center gap-4 self-end">
            <button className="w-8 h-8 flex items-center justify-center rounded-full bg-lamaYellow">
              <Image src="/filter.png" alt="" width={14} height={14} />
            </button>
            <button className="w-8 h-8 flex items-center justify-center rounded-full bg-lamaYellow">
              <Image src="/sort.png" alt="" width={14} height={14} />
            </button>
            {role === "admin" && (
              // <button className="w-8 h-8 flex items-center justify-center rounded-full bg-lamaYellow">
              //   <Image src="/plus.png" alt="" width={14} height={14} />
              // </button>
              <FormModal
                table="student"
                type="create"
                relatedData={relatedData}
              />
            )}
          </div>
        </div>
      </div>
      {/* LIST */}
      <Table columns={columns} renderRow={renderRow} data={data} />
      {/* PAGINATION */}
      <Pagination page={page} count={10} />
    </div>
  );
};

export default StudentListPage;
